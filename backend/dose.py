"""운동 용량 — 8~12주 뒤 측정에서 체력나이가 움직일 만큼.

체력나이는 국민체력100 측정(악력·윗몸말아올리기·스텝검사·앉아윗몸앞으로굽히기·
제자리멀리뛰기·체성분)에서 나온다. 그 항목이 실제로 바뀌려면 그 요인을 주 2~3회,
아래 용량으로 8~12주 해야 한다. 이보다 적으면 루틴을 빠짐없이 해도 다음 측정에서
숫자가 거의 안 움직인다 — 예전 루틴이 그랬다 (10회 2세트, 심폐 10~15분).

근거는 docs/effective_dose.md 에 정리했다.
  - WHO 2020 신체활동 지침: 성인 주 150~300분 중강도 유산소 + 주 2일 이상 근력.
  - ACSM 운동처방 지침: 근력 8~12회 × 2~4세트(초보 1~3세트) 주 2~3회, 근지구력 15~25회,
    유연성 정적 스트레칭 10~30초 × 2~4 를 주 2~3회 이상.
  - 세트 수 메타분석(Krieger 2010): 2~3세트가 1세트보다 근력 향상이 40%대 더 크다.
  - 점진적 과부하: 같은 수행량을 되풀이하면 적응이 멈춘다. 주 5~10%씩 올린다.

목적(운동 단계)에 따라 위아래로 조정하고, 어르신·재활·체력이 많이 낮은 사람은 아래쪽
값에서 시작한다. 안전 조건(건강 상태·조심할 부위)은 여기서 완화하지 않는다 — 그건
ai_recommend 의 지침과 routines 의 제외 규칙이 먼저다.
"""
from __future__ import annotations

WEEKLY_SESSIONS = 3            # 이 용량을 주 몇 번 — WHO 의 근력 2일 + 유산소를 합치면 3회는 되어야 한다
WEEKS_TO_CHANGE = "8~12주"     # 측정값이 움직이는 데 걸리는 기간

# 요인별 한 번에 하는 용량 (기본 = 성인 · 기초 체력 증진)
BASE = {
    "근력": "8~12회 × 3세트",
    "근지구력": "15~25회 × 3세트",
    "심폐지구력": "25~30분 중강도",
    "유연성": "30초 × 3",
    "민첩성": "10~15회 × 3세트",
    "순발력": "8~10회 × 3세트",
    "평형성": "30초 × 3",
    "협응력": "10~15회 × 3세트",
}
BASE_MINUTES = "30~40"          # 본운동만 (준비·정리 빼고)
BASE_EFFORT = "마지막 2~3회가 힘들 만큼 — 여유가 남으면 다음 세트를 더 무겁게·빠르게"

# 목적(운동 단계)별로 바꾸는 것. 없는 키는 BASE 그대로.
PURPOSE = {
    "다이어트": {"심폐지구력": "30~40분 중강도", "본운동 분": "35~45"},
    "기초 체력 증진": {},
    "재활 및 기능 회복": {"근력": "10~15회 × 2세트", "심폐지구력": "15~20분 가볍게", "평형성": "30초 × 3, 매일",
                       "본운동 분": "20~30", "노력": "통증 없는 범위에서 — 세트 끝에 3~4회 여유를 남겨요"},
    "수험생 체력 증진": {"심폐지구력": "20분 (1분 빠르게 · 1분 천천히 인터벌)", "본운동 분": "20~30"},
    "유연성 강화": {"유연성": "45초 × 3, 매일", "본운동 분": "25~35"},
    "벌크업": {"근력": "6~10회 × 4세트, 무겁게", "본운동 분": "40~50",
              "노력": "마지막 1~2회가 겨우 되는 무게로, 세트 사이 2~3분"},
    "근육량 늘리기": {"근력": "8~12회 × 3~4세트", "본운동 분": "35~45",
                  "노력": "8~12회째에 한계가 오는 무게로, 세트 사이 1~2분"},
    "지구력 늘리기": {"심폐지구력": "30~45분 중강도", "근지구력": "20~25회 × 3세트", "본운동 분": "35~50",
                  "노력": "가볍게 많이 — 세트 사이 30초~1분만 쉬어요"},
}
DEFAULT_PURPOSE = "기초 체력 증진"

# 어르신은 낙상 위험을 먼저 본다 — 근력은 반복을 늘리고 세트를 줄이며, 평형성을 매일. 목적보다 나중에 덮는다.
ELDER = {"근력": "10~15회 × 2~3세트", "심폐지구력": "20~30분 걷기 정도", "순발력": "8~10회 × 2세트",
         "평형성": "30초 × 3, 매일", "본운동 분": "25~35"}
ELDER_EFFORT = "숨이 조금 차고 마지막 2~3회가 힘든 정도 — 어지러우면 바로 쉬어요"

# 시간이 빡빡한 날은 짧고 진하게 — 인터벌로 심폐 자극은 지킨다
TIGHT = {"심폐지구력": "15~20분 (1분 빠르게 · 1분 천천히 인터벌)", "본운동 분": "20~30"}

LOW_START = "첫 2주는 위 표의 70~80%(세트 하나 적게)에서 시작하고, 2주 뒤부터 표대로"


def effort_for(purpose: str | None, age_gbn: str = "성인") -> str:
    """이 목적의 '얼마나 힘들게' 한 줄 — 루틴 플레이어가 세트 수 옆에 붙인다."""
    if age_gbn == "어르신":
        return ELDER_EFFORT
    return PURPOSE.get(purpose or "", {}).get("노력", BASE_EFFORT)


def dose_for(purpose: str | None, *, age_gbn: str = "성인", gap: float | None = None,
             budget: str | None = None) -> dict:
    """목적(운동 단계)·연령대·체력 격차·시간 여유 → 이번 루틴의 권장 용량.

    gap 은 (체력나이 − 실제 나이). +7세 이상이면 첫 2주는 아래쪽 값에서 시작한다 —
    routines.start_offset 이 세트를 한 구간 낮추는 것과 같은 문턱이다.
    budget 은 ai_recommend.time_budget 의 평가(빡빡함·보통·넉넉함).
    """
    목적 = purpose if purpose in PURPOSE else DEFAULT_PURPOSE
    조정 = PURPOSE[목적]
    표 = dict(BASE)
    분 = BASE_MINUTES
    for k, v in 조정.items():
        if k in 표:
            표[k] = v
    if "본운동 분" in 조정:
        분 = 조정["본운동 분"]
    if age_gbn == "어르신":
        for k, v in ELDER.items():
            if k in 표:
                표[k] = v
        분 = ELDER["본운동 분"]
    if budget == "빡빡함":
        표["심폐지구력"] = TIGHT["심폐지구력"]
        분 = TIGHT["본운동 분"]
    out = {
        "목적": 목적,
        "한 번에": 표,
        "본운동 분": 분,
        "주 횟수": WEEKLY_SESSIONS,
        "노력": effort_for(목적, age_gbn),
        "기간": WEEKS_TO_CHANGE,
        "왜": f"이 정도를 주 {WEEKLY_SESSIONS}회, {WEEKS_TO_CHANGE} 해야 다음 측정에서 체력나이가 움직입니다",
    }
    if gap is not None and gap >= 7:
        out["시작"] = LOW_START
    return out
