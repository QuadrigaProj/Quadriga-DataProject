def 채점(결과: dict | None, 사용자: dict, 기준: dict) -> dict:
    if not 결과 or not 결과.get("루틴"):
        return {"지어짐": False, "점수": 0, "항목": {"지어짐": False}}
    r = 결과["루틴"]
    steps = r.get("steps") or []
    이름들 = " ".join(str(s.get("동작") or "") for s in steps)
    본운동 = [s for s in steps if s.get("단계") == "본운동"]
    시간대 = {s.get("시간대") for s in steps if s.get("시간대")}
    항목 = {
        "지어짐": True,
        "줄수 6~12": 6 <= len(steps) <= 12,
        "시간대 셋 이상": len(시간대) >= 3,
        f"본운동 {기준['본운동최소']}개 이상": len(본운동) >= 기준["본운동최소"],
        "본운동이 절반 이상": len(본운동) * 2 >= len(steps),
        "금지 동작 없음": not any(k in 이름들 for k in 기준["금지어"]),
        "수행량 숫자로 짧게": all(re.search(r"\d", str(s.get("수행량") or "")) and len(str(s.get("수행량") or "")) <= 14 for s in steps),
        "목적이 고른 단계": (not 사용자.get("고른 운동 단계")) or r.get("목적") == 사용자["고른 운동 단계"],
        "왜 문장 있음": bool(r.get("이유")) and all(len(str(x)) <= 60 for x in r.get("이유") or []),
        "한마디 40자 안팎": bool(r.get("한마디")) and len(str(r.get("한마디"))) <= 60,
    }
    if 기준.get("필수종목"):
        항목["고른 종목 들어감"] = any(s.get("출처") == "종목" for s in steps)
    if 기준.get("점진"):
        이름, n = 기준["점진"]
        줄 = [s for s in steps if 이름 in str(s.get("동작") or "")]
        항목["점진적 과부하"] = any((m := re.search(r"(\d+)\s*회", str(s.get("수행량") or ""))) and int(m.group(1)) > n for s in 줄) if 줄 else True
    if 기준.get("조정"):
        항목["조정 언급"] = any("어렵" in str(x) or "올" in str(x) for x in (r.get("이유") or [])[:1])
    if 기준.get("실내"):
        항목["실내 대체 언급"] = any(("실내" in str(x)) or ("비" in str(x)) for x in (r.get("주의") or []) + (r.get("이유") or []) + [r.get("한마디") or ""])
    점수 = round(100 * sum(1 for v in 항목.values() if v) / len(항목))
    return {"지어짐": True, "점수": 점수, "항목": 항목}


def 원가(usage: dict | None, model: str) -> float:
    """달러. 단가는 tools 가 도는 날의 공식 표로 — 2026-06 기준 Opus 5 $5/$25, Sonnet 5 $2/$10 (100만 토큰)."""
    단가 = {"claude-opus-5": (5, 25), "claude-sonnet-5": (2, 10), "claude-haiku-4-5": (1, 5)}
    i, o = 단가.get(model, (5, 25))
    u = usage or {}
    return ((u.get("input") or 0) * i + (u.get("output") or 0) * o) / 1_000_000


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", nargs="*", default=["claude-opus-5", "claude-sonnet-5"])
    ap.add_argument("--n", type=int, default=len(USERS))
    ap.add_argument("--out", default=str(ROOT / "data" / "processed" / "ai_eval"))
    args = ap.parse_args()
    try:                                                    # 저장소 루트의 .env 를 읽는다 — 서버(uvicorn)와 같은 자리
        from dotenv import load_dotenv
        try:
            load_dotenv(ROOT / ".env")
        except UnicodeDecodeError:                          # 메모장이 CP949 로 저장한 .env
            load_dotenv(ROOT / ".env", encoding="cp949")
    except ImportError:
        pass
    if not os.getenv("ANTHROPIC_API_KEY"):
        print("ANTHROPIC_API_KEY 가 없어요. 저장소 루트의 .env 에 ANTHROPIC_API_KEY=sk-ant-... 한 줄을 넣고 다시 돌려 주세요"
              " (Render → Environment 의 값을 복사. .env 는 .gitignore 에 있어 저장소에 올라가지 않는다).")
        return 2
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    stamp = dt.datetime.now().strftime("%Y%m%d_%H%M")
    rows = []
    for 이름, 사용자, 기준 in USERS[:args.n]:
        for model in args.models:
            air.MODEL = model
            시작 = time.monotonic()
            결과 = air.compose(사용자, 사용자["연령대"], 종목ids=사용자.get("고른 종목"), 일정=기준.get("일정"))
            걸림 = round(time.monotonic() - 시작, 1)
            usage = air.take_usage()
            점 = 채점(결과, 사용자, 기준)
            rows.append({"사용자": 이름, "모델": model, "걸림초": 걸림, "usage": usage, "원가달러": round(원가(usage, model), 4),
                         "점수": 점["점수"], "항목": 점["항목"], "루틴": (결과 or {}).get("루틴")})
            print(f"{이름:28s} {model:16s} {걸림:5.1f}s  점수 {점['점수']:3d}  ${원가(usage, model):.3f}", flush=True)
    (out_dir / f"ai_model_eval_{stamp}.json").write_text(json.dumps(rows, ensure_ascii=False, indent=1), encoding="utf-8")

    # 보고서 — 표 + 문장 나란히
    md = [f"# AI 모델 비교 {stamp}\n", "| 사용자 | 모델 | 걸림 | 점수 | 원가($) | 빠진 항목 |", "|---|---|---|---|---|---|"]
    for r in rows:
        빠짐 = ", ".join(k for k, v in r["항목"].items() if not v)
        md.append(f"| {r['사용자']} | {r['모델']} | {r['걸림초']}s | {r['점수']} | {r['원가달러']} | {빠짐} |")
    for model in args.models:
        같은 = [r for r in rows if r["모델"] == model]
        if 같은:
            md.append(f"\n**{model}** 평균 점수 {sum(r['점수'] for r in 같은) / len(같은):.0f} · 평균 {sum(r['걸림초'] for r in 같은) / len(같은):.1f}초 · "
                      f"합계 ${sum(r['원가달러'] for r in 같은):.2f}")
    md.append("\n## 문장 나란히 (사람이 읽는 부분)\n")
    for 이름, _, _ in USERS[:args.n]:
        md.append(f"### {이름}")
        for model in args.models:
            r = next((x for x in rows if x["사용자"] == 이름 and x["모델"] == model), None)
            루틴 = (r or {}).get("루틴") or {}
            md.append(f"- **{model}** — {루틴.get('루틴명') or '(못 지음)'}: {루틴.get('한마디') or ''}")
            for y in (루틴.get("이유") or [])[:3]:
                md.append(f"  - {y}")
            for s in (루틴.get("steps") or [])[:12]:
                md.append(f"  - [{s.get('시간대') or ''}] {s.get('단계')} · {s.get('동작')} · {s.get('수행량')}")
    (out_dir / f"ai_model_eval_{stamp}.md").write_text("\n".join(md), encoding="utf-8")
    print("\n결과:", out_dir / f"ai_model_eval_{stamp}.md")
    return 0


