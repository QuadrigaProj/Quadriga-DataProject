def geocode(region: str) -> tuple[float, float] | None:
    """지역명/역명 문자열 → (위도, 경도). 못 찾으면 None."""
    if not region:
        return None
    q = region.strip().replace(" ", "")
    if q in PLACES:
        return PLACES[q]
    # 부분 일치 (예: "서울 강남구" → "강남구", "강남" → "강남역")
    for name, coord in PLACES.items():
        key = name.replace(" ", "")
        if key in q or q in key:
            return coord
    return None
